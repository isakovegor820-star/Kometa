def money(value: float) -> str:
    """Рубли с пробелом между разрядами: 2 233."""
    return f"{value:,.0f}".replace(",", " ")


def num1(value: float) -> str:
    """Одно десятичное с запятой: 13,6."""
    return f"{value:.1f}".replace(".", ",")


def rub1(value: float) -> str:
    """Рубли с одним знаком: 1 243,5."""
    return f"{value:,.1f}".replace(",", " ").replace(".", ",")


def pct(value: float, digits: int = 2) -> str:
    """Проценты в русской записи: 99,89 %."""
    return f"{value:.{digits}%}".replace(".", ",").replace("%", " %")



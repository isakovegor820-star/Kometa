def channel_fee_table() -> str:
    """Сколько доходит с чека при разных каналах.

    Ставка применяется к чеку один раз: 8 % СБП + 2 % конвертации = 10 %.
    Отдельная функция `net_after_partner_payout` в finmodel.py считает иначе
    (8 % и 2 % последовательно, то есть 9,8 % от остатка) — это для случая,
    когда партнёр удерживает свой процент, а банк берёт наценку за конвертацию
    с уже уменьшенной суммы. Здесь считаем консервативно: 10 % от чека.
    """
    check = average_check()
    rows = [
        "| Канал оплаты | Ставка | На руки с чека | Безубыточность схемы B |",
        "|---|---|---|---|",
    ]
    plan_b = SCENARIOS_BY_KEY["B"]
    for title, fee in (
        ("СБП (без конвертации)", 8.0),
        ("СБП + конвертация в USDT (8 % + 2 %)", DEFAULT_CHANNEL_FEE_PERCENT),
        ("Крипта (без конвертации)", 5.0),
    ):
        # константа модели: средний чек без поправки на звёзды (182 ₽), а не 181,69
        net = DEFAULT_AVERAGE_CHECK_RUB * (1 - fee / 100)
        rows.append(
            f"| {title} | {fee:.0f} % | {rub1(net)} ₽ "
            f"| {num1(plan_b.monthly_with_replacement_rub / net)} клиента |"
        )
    return "\n".join(rows)



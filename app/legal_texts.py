def html_to_markdown(text: str) -> str:
    """Перевести документ из HTML (Telegram) в Markdown для Telegra.ph.

    Telegra.ph понимает разметку при вставке: **жирный**, *курсив*, списки «•»
    и строки-заголовки. Теги <b>/<i> в редакторе остались бы обычным текстом,
    поэтому конвертируем их заранее — публикация «как есть» совпадает с ботом.
    """
    import re

    text = re.sub(r"<b>(.*?)</b>", r"**\1**", text, flags=re.DOTALL)
    text = re.sub(r"<i>(.*?)</i>", r"*\1*", text, flags=re.DOTALL)
    text = re.sub(r"<[^>]+>", "", text)
    text = text.replace("&nbsp;", " ").replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    return text.strip() + "\n"

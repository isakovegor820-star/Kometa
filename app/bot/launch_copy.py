"""Тексты «до старта»: описание бота, описание канала, первый пост.

**Зачем отдельный модуль.** Тексты, которые человек читает ДО нажатия «Начать»
(описание бота) и в шапке канала, живут не в коде бота, а в BotFather и в
настройках канала — то есть правятся руками и потому расходятся с кодом молча.
Именно так и вышло 08.10.2026: в описании бота и канала стояли «2 локации:
Германия и Нидерланды», а на сервере работали три (🇩🇪 🇫🇮 🇳🇱). Клиент видел
одно, продавали другое.

Здесь эти тексты становятся **версионируемыми**: они лежат в репозитории,
проверяются тестами на лимиты и на факты из настроек (`.env`) и накатываются
одной командой — ``python -m app.tools.apply_launch_copy --apply``.

**Правила (проверяются в** :func:`lint` **и в** ``tests/test_launch_copy.py`` **):**

* описание бота — ≤ 512 знаков, «о боте» — ≤ 120, описание канала — ≤ 255
  (лимиты Telegram; в BotFather поле обрезается молча — и текст превращается
  в обрубок);
* локации и срок пробного доступа НЕ вписаны руками, а берутся из
  ``.env``: ``LOCATION_LIST`` и ``TRIAL_DAYS``. Поменяли локацию — поменялся текст;
* ни слова про обход блокировок и ограничений доступа: публичные тексты
  проверяет ``tests/test_public_texts_clean.py`` (ч. 18 ст. 14.3 КоАП);
* первое, что видит человек, — это не «что такое VPN», а «что я получу и
  сколько это стоит»: локации, цена, пробный доступ без карты.

Тексты для вставки руками (первый пост, закреп) лежат в ``docs/КАНАЛ.md`` —
здесь только то, что можно выставить из кода.
"""

from __future__ import annotations

from dataclasses import dataclass, field

#: Лимиты Telegram. Держим их рядом с текстами: обрезка в BotFather происходит
#: молча, и «у нас всё написано» превращается в «у нас написано до середины».
DESCRIPTION_LIMIT = 512
SHORT_DESCRIPTION_LIMIT = 120
CHANNEL_DESCRIPTION_LIMIT = 255

#: Сколько локаций названо в описаниях. Список стран — один на весь проект:
#: его же подтверждает админка (``/admin/nodes``) и страница ``/status``.
LOCATION_LIST = "🇩🇪 Германия · 🇫🇮 Финляндия · 🇳🇱 Нидерланды"

#: Сколько локаций ОТРИСОВАНО на картинках бренда (баннер, обложка канала,
#: анимация) на момент последней пересборки ассетов. Число здесь, а не в
#: текстах: картинку нельзя обновить вместе с ``.env`` — её загружают в
#: Telegram руками. Поэтому связь «локаций в списке ↔ локаций на макетах»
#: держит тест: он упадёт, когда появится четвёртая локация, и напомнит
#: пересобрать ассеты командой ``bash brand/tools/build_avatar.sh``.
#:
#: История: 08.10.2026 на макетах было «2 локации» при трёх работающих — это
#: и был ответ на вопрос «почему везде говорится, что локаций два».
BRAND_ASSET_LOCATIONS = 3

#: Срок пробного доступа по умолчанию. Настоящий берётся из ``TRIAL_DAYS``.
DEFAULT_TRIAL_DAYS = 3

#: Заголовок канала. Не «VPN-сервис» (юридическая рамка), а обещание качества.
CHANNEL_TITLE = "Kometa | защищённое подключение"


def trial_days() -> int:
    """Срок пробного доступа из настроек — без импорта настроек на уровне модуля.

    Импорт внутри функции нужен тестам: они подменяют ``TRIAL_DAYS`` в окружении
    и ждут, что текст пересоберётся, а не останется от прошлого запуска.
    """
    from app.config import get_settings

    return int(get_settings().trial_days or DEFAULT_TRIAL_DAYS)


def locations() -> str:
    """Список локаций для описаний.

    ``LOCATION_LIST`` из ``.env`` важнее константы: на проде локации меняются
    (нода ушла в резерв, добавили четвёртую) — и текст обязан ехать за ними.
    """
    from app.config import get_settings

    configured = (getattr(get_settings(), "location_list", "") or "").strip()
    return configured or LOCATION_LIST


def trial_phrase() -> str:
    """«Первые 3 дня бесплатно» без ошибки в числе.

    Русский требует согласования: «Первые 3 дня», «Первый 1 день»,
    «Первых 7 дней». Ошибка в этой строке — самая заметная в описании, потому
    что она стоит последней и обещает деньги.
    """
    days = trial_days()
    tail = days % 100
    if 11 <= tail <= 14:
        word = "дней"
    else:
        word = {1: "день", 2: "дня", 3: "дня", 4: "дня"}.get(days % 10, "дней")
    if word == "день":
        return f"Первый {days} день бесплатно"
    return f"Первые {days} {word} бесплатно"


def bot_description() -> str:
    """Описание бота (``/setdescription``) — видно ДО нажатия «Начать».

    Это единственный текст, который человек читает в пустом чате, поэтому в
    нём три ответа на три вопроса: что получу (локации), сколько стоит (цена),
    чем рискую (пробный доступ без карты). Ссылки и «жмите кнопку» здесь нет:
    её и так видно под текстом.
    """
    return (
        "Kometa — защищённое подключение для телефона и компьютера.\n"
        f"Локации: {locations()} — переключение в один тап.\n"
        "Безлимитный трафик, до 3 устройств. Оплата: СБП, крипта, Telegram Stars — от 120 ₽ в месяц.\n"
        "Приложения: Happ, v2rayNG, Hiddify, Streisand — подключение за 2 минуты.\n"
        f"{trial_phrase()} — карта не нужна, автосписаний нет.\n"
        "Поддержка — в Telegram"
    )


def bot_short_description() -> str:
    """Короткое описание (``/setabouttext``) — одна строка в профиле бота.

    Лимит 120 знаков: пишем только то, что отличает, без «мы лучшие на рынке».
    """
    short = locations().replace("🇩🇪 Германия", "Германия").replace("🇫🇮 Финляндия", "Финляндия")
    short = short.replace("🇳🇱 Нидерланды", "Нидерланды")
    days = trial_days()
    # При одном дне «Первые 1 дня» — ошибка, а именно этот текст стоит последним.
    tail = "Первый день бесплатно" if days == 1 else f"Первые {days} дня бесплатно"
    return f"Защищённое подключение: безлимит, до 3 устройств, {short}. {tail}."



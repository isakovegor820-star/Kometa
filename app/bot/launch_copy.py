#: Что требуется в описании бота — по смыслу, а не по букве. Проверяет :func:`lint`.
#: Каждый пункт — (что ищем, зачем это здесь).
DESCRIPTION_REQUIRED: tuple[tuple[str, str], ...] = (
    ("локаци", "человек должен видеть, откуда будет выходить в сеть"),
    ("₽", "цена до нажатия «Начать» снимает страх «сколько это стоит»"),
    ("бесплатно", "пробный доступ — главный аргумент попробовать"),
    ("карт", "«без карты» снимает страх привязки платёжного средства"),
)

#: Требования к описанию канала: там же и юридическая часть (банк-партнёр).
CHANNEL_REQUIRED: tuple[tuple[str, str], ...] = (
    ("локаци", "канал — публичная точка входа: локации должны быть видны"),
    ("₽", "цена"),
    ("бесплатно", "пробный доступ"),
    ("бот", "ссылка на бота: канал — страховка, если бот недоступен"),
)


@dataclass(slots=True)
class LintReport:
    """Итог проверки текстов: что не влезло и чего не хватает."""

    problems: list[str] = field(default_factory=list)
    lengths: dict[str, int] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.problems

    def as_text(self) -> str:
        lines = [
            f"  {name}: {length} знаков"
            for name, length in self.lengths.items()
        ]
        if self.problems:
            lines.append("  проблемы:")
            lines.extend(f"    · {problem}" for problem in self.problems)
        else:
            lines.append("  ✅ лимиты соблюдены, обязательные факты на месте")
        return "\n".join(lines)


def lint() -> LintReport:
    """Проверить тексты без обращения к Telegram: лимиты и обязательные факты.

    Одна проверка на инструмент и на тест: то, что накатывается на прод, и то,
    что проверяется в CI, обязано быть одним и тем же кодом.
    """
    report = LintReport()
    checks: tuple[tuple[str, str, int, tuple[tuple[str, str], ...]], ...] = (
        ("описание бота", bot_description(), DESCRIPTION_LIMIT, DESCRIPTION_REQUIRED),
        ("о боте", bot_short_description(), SHORT_DESCRIPTION_LIMIT, ()),
        ("описание канала", channel_description(), CHANNEL_DESCRIPTION_LIMIT, CHANNEL_REQUIRED),
    )
    for name, text, limit, required in checks:
        report.lengths[name] = len(text)
        if len(text) > limit:
            report.problems.append(
                f"{name}: {len(text)} знаков при лимите {limit} — BotFather обрежет молча"
            )
        if "\n\n\n" in text:
            report.problems.append(f"{name}: двойная пустая строка — в Telegram выглядит как дыра")
        lowered = text.lower()
        for needle, why in required:
            if needle not in lowered:
                report.problems.append(f"{name}: нет «{needle}» — {why}")
    return report

def order_paid_text(order, *, expires: str, days: int, link: str) -> str:  # noqa: ANN001 - Order
    """Сообщение «оплата получена» с бонусом за приглашение, если он был.

    Одна точка правды: оплату подтверждают четыре разных места (бот, админ,
    вебхук, автосверка выписки), и клиент везде должен видеть одно и то же.
    """
    text = ORDER_PAID.format(expires=expires, days=days, link=link)
    reward = getattr(order, "referral_reward", None)
    if reward is not None and reward.invited_days:
        text += ORDER_PAID_REFERRAL_BONUS.format(days=reward.invited_days)
    return text

